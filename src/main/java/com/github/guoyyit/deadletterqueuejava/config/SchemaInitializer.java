package com.github.guoyyit.deadletterqueuejava.config;

import jakarta.annotation.PostConstruct;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
public class SchemaInitializer {

    private static final String[] DDL = {
            """
            CREATE TABLE IF NOT EXISTS messages (
                id VARCHAR(64) PRIMARY KEY,
                queue VARCHAR(128) NOT NULL,
                payload CLOB NOT NULL,
                status VARCHAR(16) NOT NULL,
                attempts INT NOT NULL DEFAULT 0,
                created_at BIGINT NOT NULL,
                visible_at BIGINT NOT NULL,
                leased_until BIGINT NOT NULL DEFAULT 0,
                last_error CLOB,
                policy_max_retries INT NOT NULL,
                policy_initial_backoff BIGINT NOT NULL,
                policy_max_backoff BIGINT NOT NULL,
                policy_backoff_type VARCHAR(16) NOT NULL
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS delivery_attempts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                message_id VARCHAR(64) NOT NULL,
                attempt_no INT NOT NULL,
                result VARCHAR(16) NOT NULL,
                error_reason CLOB,
                started_at BIGINT,
                finished_at BIGINT
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS dead_letters (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                message_id VARCHAR(64) NOT NULL UNIQUE,
                queue VARCHAR(128) NOT NULL,
                payload CLOB NOT NULL,
                last_reason CLOB,
                first_died_at BIGINT NOT NULL,
                last_died_at BIGINT NOT NULL,
                death_count INT NOT NULL DEFAULT 1,
                replay_count INT NOT NULL DEFAULT 0,
                status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS dead_letter_replays (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                dead_letter_id BIGINT NOT NULL,
                message_id VARCHAR(64) NOT NULL,
                outcome VARCHAR(16) NOT NULL,
                started_at BIGINT NOT NULL,
                finished_at BIGINT,
                error_reason CLOB
            )
            """,
            "CREATE INDEX IF NOT EXISTS idx_messages_dispatch ON messages(queue, status, visible_at, leased_until)",
            "CREATE INDEX IF NOT EXISTS idx_attempts_message ON delivery_attempts(message_id, attempt_no)",
            "CREATE INDEX IF NOT EXISTS idx_dead_letters_queue ON dead_letters(queue, status, first_died_at)",
            "CREATE INDEX IF NOT EXISTS idx_dead_letters_died ON dead_letters(first_died_at)",
            "CREATE INDEX IF NOT EXISTS idx_replays_dl ON dead_letter_replays(dead_letter_id, outcome)"
    };

    private final JdbcTemplate jdbcTemplate;

    public SchemaInitializer(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    @PostConstruct
    public void initialize() {
        for (String statement : DDL) {
            jdbcTemplate.execute(statement);
        }
    }
}
